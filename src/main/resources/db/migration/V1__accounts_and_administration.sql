create table app_user (
    id bigint generated by default as identity primary key,
    email varchar(254) not null unique check (email = lower(trim(email))),
    display_name varchar(120) not null default '',
    role varchar(16) not null default 'MEMBER' check (role in ('ADMIN', 'MEMBER')),
    status varchar(16) not null default 'PENDING' check (status in ('PENDING', 'APPROVED')),
    email_verified_at timestamp with time zone,
    developer boolean not null default false,
    enabled boolean not null default true,
    last_link_at timestamp with time zone,
    check (role <> 'ADMIN' or (email_verified_at is not null and status = 'APPROVED'))
);
create table bootstrap_grant (
    slot varchar(16) primary key,
    user_id bigint not null unique references app_user(id),
    granted_at timestamp with time zone not null default current_timestamp
);
create table magic_token (
    digest varchar(64) primary key,
    user_id bigint not null references app_user(id) on delete cascade,
    expires_at timestamp with time zone not null
);
create index magic_token_expiry on magic_token(expires_at);
create table link_rate (
    bucket varchar(96) primary key,
    attempts integer not null default 0,
    expires_at timestamp with time zone not null
);
create table audit_event (
    id bigint generated by default as identity primary key,
    actor varchar(254) not null,
    action varchar(64) not null,
    target_id bigint not null,
    occurred_at timestamp with time zone not null default current_timestamp
);
create table activity_group (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    description varchar(2000) not null default ''
);
create table group_member (
    group_id bigint not null references activity_group(id) on delete cascade,
    user_id bigint not null references app_user(id) on delete cascade,
    primary key(group_id, user_id)
);
create table calendar (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    description varchar(2000) not null default '',
    group_id bigint references activity_group(id) on delete set null
);
create table activity (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    description varchar(2000) not null default '',
    calendar_id bigint not null references calendar(id),
    starts_at timestamp with time zone not null,
    ends_at timestamp with time zone not null,
    check (ends_at > starts_at)
);
