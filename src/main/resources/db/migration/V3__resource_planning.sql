alter table calendar add column color varchar(7) not null default '#187a58';
alter table activity add column status varchar(20) not null default 'PLANNED'
    check (status in ('PLANNED', 'IN_PROGRESS', 'BLOCKED', 'DONE', 'CANCELLED'));
alter table activity add column version bigint not null default 0;
create index activity_period on activity(starts_at, ends_at);
create table employee (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    daily_minutes integer check (daily_minutes between 30 and 1440),
    active boolean not null default true
);
create table activity_employee (
    activity_id bigint not null references activity(id) on delete cascade,
    employee_id bigint not null references employee(id),
    primary key(activity_id, employee_id)
);
create index activity_employee_staff on activity_employee(employee_id, activity_id);
create table planning_settings (
    id integer primary key check (id = 1),
    daily_minutes integer not null default 480 check (daily_minutes between 30 and 1440),
    work_start varchar(5) not null default '07:00',
    break_start varchar(5) not null default '12:00',
    break_minutes integer not null default 60 check (break_minutes between 0 and 180)
);
